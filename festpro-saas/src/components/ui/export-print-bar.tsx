"use client"

import React from "react"
import { FileSpreadsheet, Printer } from "lucide-react"

export interface ExportColumn<T> {
  header: string
  accessor: (row: T) => string | number | null | undefined
}

interface ExportPrintBarProps<T> {
  title: string
  subtitle?: string
  data: T[]
  columns: ExportColumn<T>[]
  filename?: string
  className?: string
}

export function ExportPrintBar<T>({
  title,
  subtitle = "FestPro Festival Management System",
  data,
  columns,
  filename = "export",
  className = "",
}: ExportPrintBarProps<T>) {
  const exportToExcel = () => {
    if (!data || data.length === 0) return

    // Build CSV with UTF-8 BOM so Excel opens Malayalam / Arabic / symbols properly
    const headers = columns.map((c) => `"${c.header.replace(/"/g, '""')}"`).join(",")
    const rows = data.map((row) =>
      columns
        .map((c) => {
          const val = c.accessor(row) ?? ""
          return `"${String(val).replace(/"/g, '""')}"`
        })
        .join(",")
    )

    const csvContent = "\uFEFF" + [headers, ...rows].join("\r\n")
    const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" })
    const url = URL.createObjectURL(blob)
    const link = document.createElement("a")
    link.href = url
    link.setAttribute("download", `${filename}-${new Date().toISOString().split("T")[0]}.csv`)
    document.body.appendChild(link)
    link.click()
    document.body.removeChild(link)
  }

  const printPdf = () => {
    if (!data || data.length === 0) return

    const printWindow = window.open("", "_blank")
    if (!printWindow) return

    const tableHeaders = columns.map((c) => `<th style="border: 1px solid #cbd5e1; padding: 8px 12px; background-color: #f1f5f9; text-align: left; font-size: 12px; font-weight: bold; color: #1e293b;">${c.header}</th>`).join("")

    const tableRows = data
      .map(
        (row, idx) =>
          `<tr style="background-color: ${idx % 2 === 0 ? "#ffffff" : "#f8fafc"};">` +
          columns
            .map(
              (c) =>
                `<td style="border: 1px solid #e2e8f0; padding: 8px 12px; font-size: 11px; color: #334155;">${c.accessor(row) ?? "-"}</td>`
            )
            .join("") +
          "</tr>"
      )
      .join("")

    const html = `
      <!DOCTYPE html>
      <html>
        <head>
          <title>${title} - FestPro</title>
          <style>
            @media print {
              body { font-family: system-ui, -apple-system, sans-serif; padding: 16px; margin: 0; }
              table { width: 100%; border-collapse: collapse; margin-top: 16px; }
              @page { size: auto; margin: 15mm; }
            }
          </style>
        </head>
        <body style="font-family: system-ui, -apple-system, sans-serif; padding: 24px; color: #0f172a;">
          <div style="border-bottom: 2px solid #4f46e5; padding-bottom: 12px; margin-bottom: 16px; display: flex; justify-content: space-between; align-items: flex-end;">
            <div>
              <h1 style="font-size: 20px; font-weight: 800; margin: 0 0 4px 0; color: #1e1b4b;">${title}</h1>
              <p style="font-size: 11px; color: #64748b; margin: 0;">${subtitle}</p>
            </div>
            <div style="text-align: right; font-size: 10px; color: #94a3b8;">
              <p style="margin: 0;">Date: ${new Date().toLocaleDateString()}</p>
              <p style="margin: 2px 0 0 0;">Total Records: ${data.length}</p>
            </div>
          </div>
          <table style="width: 100%; border-collapse: collapse;">
            <thead>
              <tr>${tableHeaders}</tr>
            </thead>
            <tbody>
              ${tableRows}
            </tbody>
          </table>
          <div style="margin-top: 24px; text-align: center; font-size: 10px; color: #94a3b8; border-top: 1px solid #e2e8f0; padding-top: 8px;">
            Generated by FestPro Enterprise Festival Management Platform • festpro.ahraz.site
          </div>
        </body>
      </html>
    `

    printWindow.document.write(html)
    printWindow.document.close()
    printWindow.focus()
    setTimeout(() => {
      printWindow.print()
    }, 400)
  }

  return (
    <div className={`inline-flex items-center gap-1.5 ${className}`}>
      <button
        type="button"
        onClick={exportToExcel}
        className="inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-xl border border-slate-200/90 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold shadow-xs transition-colors"
        title="Export to Excel / CSV"
      >
        <FileSpreadsheet className="h-3.5 w-3.5 text-emerald-600" />
        <span className="hidden sm:inline">Excel</span>
      </button>

      <button
        type="button"
        onClick={printPdf}
        className="inline-flex items-center gap-1.5 px-2.5 py-1.5 rounded-xl border border-slate-200/90 bg-white hover:bg-slate-50 text-slate-700 text-xs font-semibold shadow-xs transition-colors"
        title="Print or Save as PDF"
      >
        <Printer className="h-3.5 w-3.5 text-indigo-600" />
        <span className="hidden sm:inline">PDF / Print</span>
      </button>
    </div>
  )
}
